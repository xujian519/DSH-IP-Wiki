/**
 * Pick the dictionary for one active locale id.
 * @param localeId - the locale the Client reports, such as `zh-CN`.
 * @returns the dictionary to render with.
 */
export function dictionaryFor(localeId: string): Readonly<Record<MessageKey, string>> {
  return localeId.toLowerCase().startsWith('en') ? en : zh
}
